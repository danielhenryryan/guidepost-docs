// Writes src/styles/tokens.css from the Guidepost design system's tokens.json.
// Usage: node scripts/sync-tokens.mjs <path/to/tokens.json>
// Only colors and radii are copied; the site's own type scale lives in theme.css.
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/sync-tokens.mjs <path/to/tokens.json>');
  process.exit(1);
}

const tokens = JSON.parse(readFileSync(source, 'utf8'));
const colors = new Map(tokens.color.tokens.map(token => [token.name, token.value]));

function resolve(value, theme, seen = new Set()) {
  const match = /^\{(.+)\}$/.exec(value);
  if (!match) return value;
  const name = match[1];
  if (seen.has(name)) throw new Error(`Circular color reference: ${name}`);
  seen.add(name);
  return resolve(colors.get(name)[theme], theme, seen);
}

function block(selector, theme) {
  const lines = [...colors.keys()].map(name => `  --gp-${name}: ${resolve(colors.get(name)[theme], theme)};`);
  if (theme === 'dark') {
    lines.push(...tokens.radius.tokens.map(token => `  --gp-${token.name}: ${token.value};`));
  }
  return `${selector} {\n${lines.join('\n')}\n}`;
}

const css = [
  `/* Generated by scripts/sync-tokens.mjs from the Guidepost design system (${tokens.version ?? 'unversioned'}). Do not edit. */`,
  block(':root', 'dark'),
  block(":root[data-theme='light']", 'light'),
  '',
].join('\n\n');

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log('Wrote src/styles/tokens.css');
